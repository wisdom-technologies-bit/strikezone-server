import { mkdirSync, writeFileSync } from "node:fs";
import { calibrateTable } from "../src/odds/calibrate.js";

/**
 * npm run odds:calibrate
 *
 * Plays 2,000 real carrom shots per cell of the difficulty grid through the
 * engine and writes the result to src/odds/data/. Both outputs are committed:
 * the JSON is the record of the measurement, the generated module is what the
 * server imports.
 */
async function main(): Promise<number> {
  const started = Date.now();
  const table = calibrateTable();

  mkdirSync("src/odds/data", { recursive: true });
  writeFileSync("src/odds/data/shot-table.json", `${JSON.stringify(table, null, 2)}\n`);
  writeFileSync(
    "src/odds/data/shot-table.generated.ts",
    `// Generated by npm run odds:calibrate. Do not edit by hand.\n` +
      `import type { ShotTable } from "../shot-table.js";\n\n` +
      `const shotTable: ShotTable = ${JSON.stringify(table, null, 2)};\n\n` +
      `export const SHOT_TABLE_DATA: ShotTable = shotTable;\n`,
  );

  const seconds = ((Date.now() - started) / 1000).toFixed(1);
  console.log(`calibrated ${String(table.aimErrorDegrees.length)} skill levels in ${seconds}s`);

  for (const [index, aimError] of table.aimErrorDegrees.entries()) {
    const cells = table.pocketChance[index] ?? [];
    const all = cells.flat();
    const mean = all.reduce((sum, value) => sum + value, 0) / Math.max(1, all.length);
    console.log(
      `  aim error ${String(aimError).padStart(4)} deg: mean pocket chance ${(mean * 100).toFixed(1)}%`,
    );
  }

  return 0;
}

process.exitCode = await main();
